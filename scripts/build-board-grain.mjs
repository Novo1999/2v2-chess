/**
 * Generates src/assets/board-grain.css: the wood-grain textures for the
 * "Dark wood" and "Walnut" boards, drawn from scratch as SVG noise so the app
 * ships no third-party board images.
 *
 * The streaks are deliberately faint: light and dark squares must stay clearly
 * apart at a glance, which matters more on a chessboard than realism does.
 *
 * Each texture is board-sized and holds two layers of long vertical streaks —
 * darker ones, which read on the light squares, and paler ones, which are what
 * make the grain visible on the dark squares at all. Board.tsx shows each square
 * a different patch of it, so neighbouring squares never share one grain.
 *
 *     node scripts/build-board-grain.mjs
 */

import { writeFileSync } from 'node:fs';

function layer(id, { seed, fx, fy, rgb, strength, bias }) {
  const [r, g, b] = rgb;
  return (
    `<filter id='${id}' x='0' y='0' width='100%' height='100%'>` +
    `<feTurbulence type='fractalNoise' baseFrequency='${fx} ${fy}' numOctaves='2' seed='${seed}'/>` +
    `<feColorMatrix values='0 0 0 0 ${r} 0 0 0 0 ${g} 0 0 0 0 ${b} ${strength} 0 0 0 ${bias}'/>` +
    `</filter><rect width='800' height='800' filter='url(#${id})'/>`
  );
}

function texture(dark, light) {
  const svg =
    `<svg xmlns='http://www.w3.org/2000/svg' width='800' height='800' viewBox='0 0 800 800'>` +
    layer('d', dark) +
    layer('l', light) +
    `</svg>`;
  const encoded = svg.replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E');
  return `url("data:image/svg+xml,${encoded}")`;
}

const BOARDS = {
  'dark-wood': texture(
    { seed: 4, fx: 0.16, fy: 0.0022, rgb: [0.24, 0.13, 0.04], strength: 1.3, bias: -0.6 },
    { seed: 17, fx: 0.11, fy: 0.0018, rgb: [1, 0.86, 0.6], strength: 0.9, bias: -0.47 },
  ),
  walnut: texture(
    { seed: 9, fx: 0.2, fy: 0.0026, rgb: [0.2, 0.12, 0.06], strength: 1.25, bias: -0.58 },
    { seed: 23, fx: 0.14, fy: 0.002, rgb: [0.95, 0.84, 0.68], strength: 0.85, bias: -0.45 },
  ),
};

const css =
  `/* Generated by scripts/build-board-grain.mjs — edit that, not this. */\n` +
  Object.entries(BOARDS)
    .map(([id, grain]) => `.board-theme-${id} {\n  --grain: ${grain};\n}\n`)
    .join('');

writeFileSync(new URL('../src/assets/board-grain.css', import.meta.url), css);
console.log('wrote src/assets/board-grain.css');
